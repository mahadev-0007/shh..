/// Theme icon names that could stand in for an SF Symbol, best first.
pub fn candidates(sf: &str) -> &'static [&'static str] {
    let base = sf.strip_suffix(".fill").unwrap_or(sf);
    MAP.iter().find(|(k, _)| *k == base || *k == sf).map(|(_, v)| *v).unwrap_or(&[])
}

/// The icon to draw for an SF Symbol name on this desktop, if the current
/// theme has one. A name that is already a theme icon is used as it is.
pub fn themed(sf: &str) -> Option<String> {
    let theme = gtk::IconTheme::for_display(&gdk::Display::default()?);
    if sf.ends_with("-symbolic") && theme.has_icon(sf) {
        return Some(sf.to_string());
    }
    candidates(sf).iter().find(|n| theme.has_icon(n)).map(|n| n.to_string())
}

pub fn emoji(query: &str) -> Vec<&'static str> {
    let q = query.trim().to_lowercase();
    EMOJI.iter().filter(|(e, k)| q.is_empty() || k.contains(&q) || *e == q).map(|(e, _)| *e).collect()
}

/// SF names the picker can offer: mapped, drawable here, matching the query.
pub fn symbols(query: &str) -> Vec<&'static str> {
    let q = query.trim().to_lowercase();
    SF_SYMBOLS
        .iter()
        .filter(|s| q.is_empty() || s.contains(&q))
        .filter(|s| themed(s).is_some())
        .copied()
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fill_variants_share_a_mapping() {
        assert_eq!(candidates("folder.fill"), candidates("folder"));
        assert_eq!(candidates("server.rack")[0], "network-server-symbolic");
        assert_eq!(candidates("terminal.fill")[0], "utilities-terminal-symbolic");
        assert!(candidates("no.such.symbol").is_empty());
    }

    #[test]
    fn most_of_the_mac_list_is_mapped() {
        let mapped = SF_SYMBOLS.iter().filter(|s| !candidates(s).is_empty()).count();
        assert!(mapped * 10 >= SF_SYMBOLS.len() * 8, "{mapped}/{}", SF_SYMBOLS.len());
        for (_, names) in MAP {
            assert!(names.iter().all(|n| n.ends_with("-symbolic")));
        }
    }

    #[test]
    fn emoji_search_uses_keywords() {
        assert!(emoji("docker").contains(&"🐳"));
        assert_eq!(emoji("").len(), EMOJI.len());
        assert!(emoji("zzzz").is_empty());
    }
}
